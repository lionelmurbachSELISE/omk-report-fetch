def lookup_tcpos(omk_name: str) -> tuple[str, str] | tuple[None, None]:
    """Return (Artikel Nr., Artikel Bezeichnung) for an OMK product name, or (None, None)."""
    nr = _OMK_TO_NR.get(omk_name.strip().lower())
    if nr is None:
        return None, None
    return nr, TCPOS_ARTICLES.get(nr, omk_name)
